#!/usr/bin/env python3
"""Embed web sources in a deterministic flash registry, without third-party tools."""
import argparse
import hashlib
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parents[1]
MIMES = {'.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
         '.js': 'text/javascript; charset=utf-8', '.png': 'image/png'}


def render_header(source_dir):
    source_dir = Path(source_dir)
    index = source_dir / 'index.html'
    if not index.is_file():
        raise ValueError(f'Missing entry point: {index}')
    sources = [index] + sorted(
        (p for p in source_dir.iterdir() if p.is_file() and p.suffix in ('.css', '.js', '.png')),
        key=lambda p: p.name)
    lines = ['// Generated by scripts/build_web.py. Edit web/ sources instead.',
             '#pragma once', '#include <Arduino.h>', '#include <stddef.h>',
             '#include <string.h>', '', 'namespace reflectormic_web {',
             'struct Asset {', '  const char *path;', '  const char *mime;',
             '  const char *data;', '  size_t size;', '};', '']
    entries = []
    symbols = set()
    for source in sources:
        if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*', source.name):
            raise ValueError(f'Unsupported asset filename: {source.name}')
        if source.suffix == '.png':
            content = source.read_bytes()
            if not content.startswith(b'\x89PNG\r\n\x1a\n'):
                raise ValueError(f'Invalid PNG asset: {source.name}')
            symbol = 'asset_' + re.sub(r'[^A-Za-z0-9_]', '_', source.name)
            if symbol in symbols:
                raise ValueError(f'Asset symbol collision: {source.name}')
            symbols.add(symbol)
            lines.append(f'static const char {symbol}[] PROGMEM =')
            for offset in range(0, len(content), 32):
                lines.append('  "' + ''.join(f'\\x{b:02x}' for b in content[offset:offset+32]) + '"')
            lines.append(';')
            entries.append(f'  {{"/assets/{source.name}", "image/png", {symbol}, sizeof({symbol}) - 1}},')
            continue
        # Canonicalize checkout line endings; encode in UTF-8 without a BOM.
        content = source.read_text(encoding='utf-8-sig')
        if '\0' in content:
            raise ValueError(f'NUL byte in text asset: {source.name}')
        digest = hashlib.sha256(content.encode('utf-8')).hexdigest()
        delimiter = 'RM' + digest[:12]
        if f'){delimiter}"' in content:
            raise ValueError(f'Raw-string delimiter collision: {source.name}')
        symbol = 'asset_' + re.sub(r'[^A-Za-z0-9_]', '_', source.name)
        if symbol in symbols:
            raise ValueError(f'Asset symbol collision: {source.name}')
        symbols.add(symbol)
        lines.extend([f'// {source.name} sha256:{digest}',
                      f'static const char {symbol}[] PROGMEM = R"{delimiter}({content}){delimiter}";', ''])
        path = '/' if source == index else '/assets/' + source.name
        entries.append(f'  {{"{path}", "{MIMES[source.suffix]}", {symbol}, sizeof({symbol}) - 1}},')
    lines.extend(['static const Asset kAssets[] = {', *entries, '};',
                  'static constexpr size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);', '',
                  'inline const Asset *findAsset(const char *path) {',
                  '  if (!path) return nullptr;',
                  '  for (size_t i = 0; i < kAssetCount; ++i) {',
                  '    if (strcmp(kAssets[i].path, path) == 0) return &kAssets[i];',
                  '  }', '  return nullptr;', '}', '}  // namespace reflectormic_web', ''])
    return '\n'.join(lines).encode('utf-8')


def build_assets(source_dir, output, check=False):
    """Return True if output already matches; otherwise atomically regenerate it."""
    output = Path(output)
    generated = render_header(source_dir)
    current = output.read_bytes() if output.is_file() else None
    if current == generated:
        return True
    if check:
        return False
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=output.parent, prefix=output.name + '.',
                                         suffix='.tmp', delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(generated)
        temporary.replace(output)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()
    return False


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'web', help='Web source directory')
    parser.add_argument('--output', type=Path,
                        default=ROOT / '.pio/web-assets/reflectormic_web_assets.h',
                        help='Generated header (default: ignored .pio/web-assets/)')
    parser.add_argument('--check', action='store_true', help='Fail if the output is missing or stale')
    args = parser.parse_args(argv)
    try:
        unchanged = build_assets(args.source, args.output, check=args.check)
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(2, f'Web asset generation failed: {error}\n')
    if args.check and not unchanged:
        parser.exit(1, f'Web assets are missing or stale: {args.output}\n')
    print(f'{"Up to date" if unchanged else "Generated"}: {args.output}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
